// Builds WarLegendRaidTool/TransportsData.lua from the data.lua of NauticusClassicResurrected (MIT, psynct).
// Usage: node tools/gen-transports.js path/to/NauticusClassicResurrected
// Only the Forever (Interface 16001) data is kept; route points are packed as absolute "x,y,t[|flags]" strings.
const fs = require("fs");
const path = require("path");
const lp = require("luaparse");
const dir = process.argv[2];
if (!dir) { console.error("give the Nauticus folder"); process.exit(1); }
const src = fs.readFileSync(path.join(dir, "data.lua"), "utf8").replace(/^﻿/, "");
const fr = {};
for (const m of fs.readFileSync(path.join(dir, "Locales/locale.frFR.lua"), "utf8").matchAll(/L\["([^"]+)"\]\s*=\s*"([^"]*)"/g)) fr[m[1]] = m[2];
const ast = lp.parse(src, { comments: false, luaVersion: "5.1" });
const ARROW = " <-> ";
function ev(n) {
    switch (n.type) {
        case "StringLiteral": return n.value !== null && n.value !== undefined ? n.value : n.raw.slice(1, -1);
        case "NumericLiteral": return n.value;
        case "BooleanLiteral": return n.value;
        case "UnaryExpression": return -ev(n.argument);
        case "Identifier": if (n.name === "ARROW") return ARROW; throw new Error("id " + n.name);
        case "IndexExpression": return ev(n.index);
        case "BinaryExpression": if (n.operator === "..") return ev(n.left) + ev(n.right); throw new Error("op");
        case "TableConstructorExpression": {
            const t = {}; let i = 1;
            for (const f of n.fields) {
                if (f.type === "TableKey") t[ev(f.key)] = ev(f.value);
                else if (f.type === "TableKeyString") t[f.key.name] = ev(f.value);
                else t[i++] = ev(f.value);
            }
            return t;
        }
        default: throw new Error("node " + n.type);
    }
}
const D = {};
for (const st of ast.body) {
    if (st.type === "AssignmentStatement" && st.variables[0].type === "MemberExpression") {
        D[st.variables[0].identifier.name] = ev(st.init[0]);
    }
}
const arr = (t) => Object.keys(t).map(Number).sort((a, b) => a - b).map((k) => t[k]);
const ids = Object.keys(D.transports).map(Number).sort((a, b) => a - b);
const out = [];
let total = 0;
for (const id of ids) {
    const tr = D.transports[id];
    const fe = D.transportOverrides_forever[id];
    const name = (fe && fe.name) || tr.name;
    const rtt = (D.rtts_forever && D.rtts_forever[id]) || D.rtts[id];
    const plats = (D.platforms_forever && D.platforms_forever[id]) || D.platforms[id];
    const pf = D.packedData_forever[id];
    const packed = (pf && Object.keys(pf).length) ? pf : D.packedData[id];
    let x = 0, y = 0, t = 0;
    const pts = [];
    for (const k of Object.keys(packed).map(Number).sort((a, b) => a - b)) {
        const f = packed[k].split(":");
        x += parseFloat(f[0]); y += parseFloat(f[1]); t += parseFloat(f[2]);
        const flags = [];
        for (let j = 5; j < f.length; j++) {
            const c = f[j].slice(0, 4);
            if (c === "plat") flags.push("p" + f[j].slice(4));
            else if (c === "trig") flags.push(f[j].slice(4) === "0" ? "u" : "t");
            else if (c === "zone") flags.push("z");
            else if (c === "jump") flags.push("j");
            else if (c === "rawp") flags.push("r");
        }
        pts.push(x.toFixed(6) + "," + y.toFixed(6) + "," + t.toFixed(3) + (flags.length ? "|" + flags.join("") : ""));
    }
    total += pts.length;
    const zones = [];
    const zs = Object.assign({}, D.transitZones);
    for (const z of Object.keys(D.transitZones_forever || {})) zs[z] = Object.assign({}, zs[z], D.transitZones_forever[z]);
    for (const z of Object.keys(zs)) if (zs[z][id]) zones.push(Number(z));
    out.push({
        id, vessel: tr.vessel_name, kind: tr.ship_type, name, faction: tr.faction, rtt,
        coords: D.coordsType[id], raw: (D.rawInstance && D.rawInstance[id]) || 0,
        dirx: !!(D.checkTriggerDirection[id] && D.checkTriggerDirection[id].x),
        plats: arr(plats).map((p) => p.name), zones, pts: pts.join(";"),
    });
}
const q = (s) => JSON.stringify(s);
let lua = "-- WarLegend RaidTool - Transports data (generated by tools/gen-transports.js: do not edit by hand)\n"
    + "-- Route points of the boats, zeppelins and trams, from NauticusClassicResurrected 1.5.4 (MIT, (c) 2020 psynct).\n"
    + "-- Point: x,y,t|flags ; x,y = Azeroth map fraction (or world coords when coords >= 0 / flag r), t = seconds since the\n"
    + "-- start of the cycle, flags: pN platform N, t trigger, u trigger (after), z zoning, j jump, r raw point.\n"
    + "local W = WLRT\nW.TransportData = {\n";
for (const o of out) {
    lua += "    [" + o.id + "] = { vessel = " + q(o.vessel) + ", kind = " + q(o.kind) + ", name = " + q(o.name) + ", faction = " + q(o.faction)
        + ", rtt = " + o.rtt + ", coords = " + o.coords + ", raw = " + o.raw + (o.dirx ? ", dirx = true" : "")
        + ",\n        plats = {" + o.plats.map(q).join(", ") + "},\n        zones = {" + o.zones.join(", ") + "},\n        pts = " + q(o.pts) + ",\n    },\n";
}
lua += "}\n";
const frKeys = new Set();
for (const o of out) for (const s of [o.vessel, o.name, ...o.plats]) for (const piece of s.split(/ <-> |, /)) frKeys.add(piece);
lua += "W.TransportNamesFR = {\n";
for (const k of [...frKeys].sort()) if (fr[k] && fr[k] !== k) lua += "    [" + q(k) + "] = " + q(fr[k]) + ",\n";
lua += "}\n";
fs.writeFileSync(path.join(__dirname, "../WarLegendRaidTool/TransportsData.lua"), lua);
console.log("transports", out.length, "points", total, "bytes", lua.length);
