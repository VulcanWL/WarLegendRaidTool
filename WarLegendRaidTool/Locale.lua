-- Language: "auto" follows the game client, "fr" / "en" are chosen in the window (needs a reload).
-- The saved choice is only known at ADDON_LOADED, after every file has run: until then texts stay in
-- English, and tables built while loading are translated again with W.TranslateField.
W.IS_FR = GetLocale and GetLocale() == "frFR" -- client language
W.LANG = "en"
local EMPTY = {}
local active = EMPTY

function W.L(s)
    return active[s] or s
end

-- Modules add their own French strings
-- Every file of the main addon runs before the language is known (ADDON_LOADED): the French texts are kept then,
-- and freed by SetLanguage when the language is English. Files loaded later (the raid addon) skip them in English.
local languageKnown = false
function W.AddFR(t)
    if languageKnown and W.LANG == "en" then return end -- English: the French texts are never read
    for k, v in pairs(t) do FR[k] = v end
end

function W.SetLanguage(choice)
    languageKnown = true
    local fr = choice == "fr" or (choice ~= "en" and W.IS_FR)
    active = fr and FR or EMPTY
    W.LANG = fr and "fr" or "en"
    -- in English the French texts are never read: free them (changing language needs a reload)
    if not fr then
        for k in pairs(FR) do FR[k] = nil end
    end
end

-- Table entries filled at load time (English keys) get translated once the language is set
function W.TranslateField(list, field)
    W.OnReady(function()
        for _, e in pairs(list) do
            if type(e[field]) == "string" then e[field] = W.L(e[field]) end
        end
    end)
end

-- string.upper ignores accented letters: uppercase them by hand
local ACCENTS = { ["é"] = "É", ["è"] = "È", ["ê"] = "Ê", ["à"] = "À", ["â"] = "Â", ["ô"] = "Ô", ["û"] = "Û", ["ù"] = "Ù", ["î"] = "Î", ["ç"] = "Ç", ["ë"] = "Ë", ["ï"] = "Ï" }
function W.Upper(s)
    s = string.upper(s or "")
    for low, up in pairs(ACCENTS) do s = s:gsub(low, up) end
    return s
end
